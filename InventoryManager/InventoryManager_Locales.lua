for localeName, localeExtra in pairs(extraTranslations) do
    local localeTable = translations[localeName]
    for key, value in pairs(localeExtra) do
        localeTable[key] = value
    end
end

local locale = GetLocale and GetLocale() or "enUS"
local localeTranslations = translations[locale] or {}

function IM:L(text, ...)
    local translated = localeTranslations[text] or text
    if select("#", ...) > 0 then
        return string.format(translated, ...)
    end
    return translated
end
